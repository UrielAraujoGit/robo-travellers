import type { ExoplanetType } from "../schemas/exoplanet.type";
import { formatDistance, formatOrbitalPeriod } from "./exoplanet-format";
import { planetSurface } from "./planet-surface";

/** Equilibrium temperatures [K] loosely compatible with liquid water on the surface. */
const HABITABLE_TEMPERATURE: [number, number] = [180, 310];

/** Whether a rocky or ocean planet sits at a temperature compatible with liquid water. */
export function inHabitableZone(planet: ExoplanetType) {
  const surface = planetSurface(planet);
  const [min, max] = HABITABLE_TEMPERATURE;
  return (
    (surface === "rocky" || surface === "ocean") &&
    planet.pl_eqt != null &&
    planet.pl_eqt >= min &&
    planet.pl_eqt <= max
  );
}

